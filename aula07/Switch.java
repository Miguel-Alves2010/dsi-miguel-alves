package aula07;

public class Switch {
    public static void main(String[] args) {
    


// O switch serve para escolher entre várias opções.
// Ele é parecido com vários if e else juntos.

// Nesse exemplo, a variável "aula" guarda um número.
// Dependendo do número, o programa mostra uma aula do horário de segunda feira (2DA).
    int aula = 6;
    switch (aula) {
        case 1:
        System.out.println("Desenvolvimento de sistemas");
        break;

        case 2: 
        System.out.println("Desenvolvimento de sistemas");
        break;

        case 3: 
        System.out.println("Desenvolvimento de sistemas");
        break;

        case 4:
        System.out.println("Ética e cidadania organizacional");
        break;

        case 5:
        System.out.println("Português");
        break;

        case 6:
        System.out.println("Português");
        break;
    }

    
    }
}

